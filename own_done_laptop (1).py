x = df.drop(columns=["Price"])
y = df["Price"]

x.shape

y.shape

x_train, x_test, y_train, y_test = train_test_split(x,y,test_size=0.2,random_state=22)

cat_train = x_train[["Brand"]]
cat_test = x_test[["Brand"]]

cat_train.shape

cat_test.shape

o = OneHotEncoder(sparse_output=False,handle_unknown="ignore")
cat_x_train = o.fit_transform(cat_train)
cat_x_train = pd.DataFrame(cat_x_train,columns=o.get_feature_names_out(["Brand"]),index=cat_train.index)

cat_x_train.head(3)

x_train.head(3)

x_train_new = x_train.drop(columns=["Brand"])
x_train_new = x_train_new.join(cat_x_train)

x_train_new.head(3)

cat_x_test = o.transform(cat_test)
cat_x_test = pd.DataFrame(cat_x_test,columns=o.get_feature_names_out(["Brand"]),index=cat_test.index)

cat_x_test.head(3)

x_test.head(3)

x_test_new = x_test.drop(columns=["Brand"])
x_test_new = x_test_new.join(cat_x_test)

x_test_new.head(3)

lr = LinearRegression()
lr.fit(x_train_new,y_train)

lrypt = lr.predict(x_test_new)

r = Ridge(alpha=2.0)
r.fit(x_train_new,y_train)

rypt = r.predict(x_test_new)

l = Lasso(alpha=0.5)
l.fit(x_train_new,y_train)

lypt = l.predict(x_test_new)

p = PolynomialFeatures(degree=2)
x_train_poly = p.fit_transform(x_train_new)
x_test_poly = p.transform(x_test_new)

pr = LinearRegression()
pr.fit(x_train_poly,y_train)

prypt = pr.predict(x_test_poly)

dt = DecisionTreeRegressor(random_state=22)
dt.fit(x_train_new,y_train)

dtypt = dt.predict(x_test_new)

sc = StandardScaler()
x_train_scaled = sc.fit_transform(x_train_new)
x_test_scaled = sc.transform(x_test_new)

kn = KNeighborsRegressor(n_neighbors=5)
kn.fit(x_train_scaled,y_train)

knypt = kn.predict(x_test_scaled)

rf = RandomForestRegressor(n_estimators=100,random_state=22)
rf.fit(x_train_new,y_train)

rfypt = rf.predict(x_test_new)

print(f"LinearRegression mse: {mean_squared_error(y_test,lrypt)}")
print(f"LinearRegression rmse: {root_mean_squared_error(y_test,lrypt)}")
print(f"LinearRegression r2: {r2_score(y_test,lrypt)}")

print(f"Ridge mse: {mean_squared_error(y_test,rypt)}")
